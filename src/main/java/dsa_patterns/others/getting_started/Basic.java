package basics.getting_started;

public class Basic {

    public static void main(String[] args) {
        System.out.println("Hello World");
        System.out.println("Hello World");

        System.out.println();

        // star pattern - using system class
        System.out.println("*");
        System.out.println("**");
        System.out.println("***");
        System.out.println("****");
        System.out.println("*****");

        System.out.println();

        // star pattern - using system class - single line
        System.out.print("*\n**\n***\n****\n*****");

        System.out.println();

        // print Z shape in java.
        /*
         * * * * *
         *
         *
         *
         * * * * *
         */

        System.out.println("* * * * *");
        System.out.println("      *");
        System.out.println("    *");
        System.out.println("  *");
        System.out.println("* * * * *");

        System.out.println();

        System.out.println("* * * * *\n      *\n    *\n  *\n* * * * *");

    }

}
